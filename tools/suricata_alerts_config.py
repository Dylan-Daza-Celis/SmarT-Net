"""Create a private wrapper retaining original outputs and adding one alert-only logger.

Never edits the base, starts a sensor, or changes a service. Refuses ambiguous include/alias layouts.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import yaml
from yaml.nodes import MappingNode, SequenceNode, ScalarNode

FRAGMENT = Path(__file__).resolve().parents[1]/'config/suricata/alert-logger.yaml'


class ConfigError(ValueError): pass


def read(path):
    with path.open('rb') as stream: data=stream.read(2*1024*1024+1)
    if len(data)>2*1024*1024: raise ConfigError('configuration_too_large')
    return data,data.decode('utf-8-sig')


def base_outputs(base):
    raw,source=read(base)
    root=yaml.compose(source)
    if not isinstance(root,MappingNode):raise ConfigError('base_must_be_mapping')
    values={}
    for key,value in root.value:
        if not isinstance(key,ScalarNode) or key.value in values:raise ConfigError('ambiguous_top_level_keys')
        values[key.value]=value
    if 'include' in values:raise ConfigError('active_includes_require_manual_review')
    sequence=values.get('outputs')
    if not isinstance(sequence,SequenceNode) or sequence.flow_style:raise ConfigError('literal_block_outputs_required')
    start=source.rfind('\n',0,sequence.start_mark.index)+1
    block=source[start:sequence.end_mark.index].rstrip()+'\n'
    # Parsing the extracted block catches aliases depending on anchors outside outputs.
    original=yaml.safe_load('outputs:\n'+block)['outputs']
    if not isinstance(original,list):raise ConfigError('invalid_outputs')
    return raw,block,original


def create(base, output, eve_file='smartir-alerts.json'):
    base,output=Path(base).resolve(),Path(output).absolute()
    if base==output.resolve(): raise ConfigError('output_is_base')
    if not isinstance(eve_file,str) or not eve_file or eve_file.endswith('/') or any(ord(c)<32 for c in eve_file) or '\\' in eve_file:
        raise ConfigError('invalid_eve_path')
    path=PurePosixPath(eve_file)
    if '..' in path.parts or '%' in eve_file or path.name in ('','.','..'):raise ConfigError('invalid_eve_path')
    raw,block,original=base_outputs(base)
    for item in original:
        if not isinstance(item,dict):raise ConfigError('invalid_output_entry')
        for settings in item.values():
            if isinstance(settings,dict) and isinstance(settings.get('filename'),str):
                if PurePosixPath(settings['filename']).name==path.name:raise ConfigError('eve_filename_collision')
    fragment=yaml.safe_load(FRAGMENT.read_text(encoding='utf-8'))
    fragment['eve-log']['filename']=eve_file
    addition=yaml.safe_dump([fragment],sort_keys=False,allow_unicode=False)
    # Use a separate YAML document. Lists are replaced by Suricata; copying all original entries is essential.
    digest=hashlib.sha256(raw).hexdigest()
    text=('%YAML 1.1\n---\n# Generated by SmartIR-Net; base is never overwritten.\n'
          '# smartir-base-sha256: '+digest+'\ninclude: '+json.dumps(str(base),ensure_ascii=True)+
          '\noutputs:\n'+block+'\n'+''.join('  '+line+'\n' for line in addition.splitlines()))
    effective=yaml.safe_load(text)['outputs']
    if effective[:-1]!=original or effective[-1]['eve-log']['types']!=['alert']:raise ConfigError('outputs_not_preserved')
    fd=os.open(output,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
    with os.fdopen(fd,'w',encoding='utf-8',newline='\n') as stream:
        stream.write(text);stream.flush();os.fsync(stream.fileno())
    if base.read_bytes()!=raw:raise ConfigError('base_changed_during_generation')
    return {'base_sha256':digest,'preserved_outputs':len(original),'added_outputs':1,'types':['alert']}


def verify(output):
    _,text=read(Path(output))
    match=re.search(r'^# smartir-base-sha256: ([0-9a-f]{64})$',text,re.MULTILINE)
    config=yaml.safe_load(text)
    if not match or not isinstance(config,dict) or not isinstance(config.get('include'),str):raise ConfigError('invalid_generated_wrapper')
    raw,_,original=base_outputs(Path(config['include']))
    if hashlib.sha256(raw).hexdigest()!=match[1]:raise ConfigError('base_changed_regenerate_wrapper')
    outputs=config.get('outputs')
    expected=yaml.safe_load(FRAGMENT.read_text(encoding='utf-8'))['eve-log']
    if not isinstance(outputs,list) or len(outputs)!=len(original)+1 or outputs[:-1]!=original:
        raise ConfigError('outputs_changed')
    added=outputs[-1].get('eve-log') if isinstance(outputs[-1],dict) else None
    if not isinstance(added,dict) or any(added.get(k)!=v for k,v in expected.items() if k!='filename'):
        raise ConfigError('dedicated_logger_changed')
    return {'base_unchanged':True,'base_sha256':match[1]}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base',type=Path)
    parser.add_argument('--output',type=Path)
    parser.add_argument('--eve-file',default='smartir-alerts.json')
    parser.add_argument('--check',type=Path)
    args=parser.parse_args()
    try:
        if args.check:result=verify(args.check)
        elif args.base and args.output:result=create(args.base,args.output,args.eve_file)
        else:parser.error('Use --base/--output or --check')
        print(json.dumps(result,sort_keys=True))
    except (ConfigError,OSError,UnicodeError,yaml.YAMLError,RecursionError):
        # Actual user configs can contain credentials; never echo their contents/parser snippets.
        raise SystemExit('Configuration rejected; check paths, literal outputs, includes, collisions and file permissions') from None


if __name__=='__main__':main()
